"""AI-generated image check based on file METADATA, not on a machine-learning model.

Image generators and editors usually leave a trail inside the file, and plain code can read it:

  * C2PA / Content Credentials manifests (OpenAI DALL-E / ChatGPT, Adobe Firefly, Microsoft, Google ...)
  * IPTC / XMP ``DigitalSourceType`` = trainedAlgorithmicMedia (the industry flag for "made by generative AI")
  * PNG text chunks written by Stable Diffusion WebUI ("parameters": Steps / Sampler / CFG scale), ComfyUI
    ("prompt" + "workflow"), InvokeAI, NovelAI, Fooocus ...
  * generator names in EXIF Software / description fields, XMP and comments (Midjourney, DALL-E, Firefly ...)

Limits (by design, stated to the user): metadata can be stripped by a screenshot, a re-save or a messaging app,
so a clean file proves nothing. Invisible watermarks such as SynthID need the vendor's own detector. This check
only catches generated images that still carry their metadata, which is a lot of them in practice.

Only metadata regions of the container (JPEG APPn/COM segments, PNG text/XMP/C2PA chunks, WebP EXIF/XMP chunks)
are scanned, never the compressed pixel data, so random pixel bytes cannot trigger a false match.
"""

import re
import struct
import zlib
from io import BytesIO

from PIL import Image

AUTHENTICITY_VERSION = "metadata-v2"

LIMITATIONS = (
    "Metadata-only check: it flags generated images that still carry their metadata. A screenshot or re-save strips "
    "it, so a clean result does not prove the photo is real."
)

# IPTC DigitalSourceType values that mean "generated by AI / an algorithm" (matched case-insensitively)
SOURCE_TYPES = (
    b"compositewithtrainedalgorithmicmedia",
    b"trainedalgorithmicmedia",
    b"algorithmicmedia",
)

# (label, pattern) - patterns are specific names, never short generic words
GENERATORS = [
    ("DALL-E / OpenAI", re.compile(rb"dall[-\s\.]?e\b|dall\xc2\xb7e|openai|chatgpt|gpt-image", re.I)),
    ("Midjourney", re.compile(rb"midjourney", re.I)),
    ("Stable Diffusion", re.compile(rb"stable[\s_-]?diffusion|stability[\s\.]?ai|dreamstudio|\bsdxl\b", re.I)),
    ("Adobe Firefly", re.compile(rb"adobe[\s_-]?firefly|\bfirefly\b", re.I)),
    ("Google AI (Imagen / Gemini)", re.compile(rb"made with google ai|google imagen|\bimagen[\s-]?\d|synthid", re.I)),
    ("Microsoft Designer / Bing Image Creator", re.compile(rb"microsoft designer|bing image creator", re.I)),
    ("Leonardo.Ai", re.compile(rb"leonardo\.ai", re.I)),
    ("Ideogram", re.compile(rb"ideogram", re.I)),
    ("NovelAI", re.compile(rb"novelai", re.I)),
    ("Fooocus", re.compile(rb"fooocus", re.I)),
    ("InvokeAI", re.compile(rb"invokeai|sd-metadata", re.I)),
    ("Craiyon", re.compile(rb"craiyon", re.I)),
    ("NightCafe", re.compile(rb"nightcafe", re.I)),
    ("Runway", re.compile(rb"runwayml", re.I)),
    ("Canva Magic Media", re.compile(rb"magic media", re.I)),
    ("Flux (Black Forest Labs)", re.compile(rb"black forest labs|flux\.1", re.I)),
    ("Playground AI", re.compile(rb"playground[\s_-]?ai", re.I)),
    ("Meta AI", re.compile(rb"imagined with ai|meta ai\b|emu image|llama image", re.I)),
    ("Grok / xAI", re.compile(rb"\bgrok\b|x\.?ai aurora|\baurora\b.{0,20}x\.?ai", re.I)),
    ("Microsoft Copilot", re.compile(rb"microsoft copilot|copilot designer|image creator from microsoft", re.I)),
    ("Amazon Titan / Nova", re.compile(rb"amazon titan image|nova canvas|nova reel", re.I)),
    ("ByteDance Seedream / Dreamina", re.compile(rb"seedream|dreamina|doubao|jimeng", re.I)),
    ("Recraft / Krea / Lexica", re.compile(rb"recraft\.ai|krea\.ai|lexica\.art", re.I)),
    ("Google Gemini image", re.compile(rb"nano banana|gemini[\s-]?\d?(\.\d)?[\s-]?(flash|pro)?[\s-]?image", re.I)),
    ("Generic AI label", re.compile(rb"ai[\s-]generated|generated (by|with|using) ai|created (by|with|using) ai|made with ai|generative ai", re.I)),
]

# Image sizes that generators output a lot (all multiples of 64)
_COMMON_AI_SIZES = {
    (512, 512), (768, 768), (1024, 1024), (1024, 1792), (1792, 1024), (1344, 768), (768, 1344),
    (1152, 896), (896, 1152), (1216, 832), (832, 1216), (1536, 1536), (2048, 2048), (512, 768), (768, 512),
}


# ── container parsing: collect only the metadata regions ──────────────────────────────────────
def _jpeg_metadata(data: bytes) -> tuple[bytes, bool]:
    blobs, app11, c2pa, i = [], [], False, 2
    while i + 4 <= len(data) and data[i] == 0xFF:
        marker = data[i + 1]
        if marker == 0xDA:  # start of scan: only pixel data follows
            break
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        (length,) = struct.unpack(">H", data[i + 2:i + 4])
        seg = data[i + 4:i + 2 + length]
        if 0xE0 <= marker <= 0xEF or marker == 0xFE:
            blobs.append(seg)
            if marker == 0xEB:  # JUMBF / C2PA boxes live in APP11
                app11.append(seg[8:] if seg[:2] == b"JP" else seg)  # drop the 'JP' + instance + sequence header
                if b"jumb" in seg or b"c2pa" in seg:
                    c2pa = True
        i += 2 + length
    if app11:
        blobs.append(b"".join(app11))  # a string split across two APP11 segments becomes whole again
    eoi = data.rfind(b"\xff\xd9")
    if 0 < eoi < len(data) - 2 and len(data) - eoi < 2_000_000:
        blobs.append(data[eoi + 2:])  # some tools append XMP/C2PA after the end-of-image marker
    return b"\n".join(blobs), c2pa


def _png_metadata(data: bytes) -> tuple[bytes, bool, dict]:
    blobs, c2pa, text, i = [], False, {}, 8
    while i + 8 <= len(data):
        length, ctype = struct.unpack(">I4s", data[i:i + 8])
        body = data[i + 8:i + 8 + length]
        if ctype == b"tEXt":
            key, _, val = body.partition(b"\x00")
            text[key.decode("latin-1")] = val.decode("latin-1")
            blobs.append(body)
        elif ctype == b"zTXt":
            key, _, rest = body.partition(b"\x00")
            try:
                val = zlib.decompress(rest[1:])
            except zlib.error:
                val = b""
            text[key.decode("latin-1")] = val.decode("utf-8", "replace")
            blobs.append(key + b"\x00" + val)
        elif ctype == b"iTXt":
            key, _, rest = body.partition(b"\x00")
            flag, method = rest[0:1], rest[1:2]
            rest = rest[2:]
            _, _, rest = rest.partition(b"\x00")   # language tag
            _, _, val = rest.partition(b"\x00")    # translated keyword
            if flag == b"\x01":
                try:
                    val = zlib.decompress(val)
                except zlib.error:
                    val = b""
            text[key.decode("latin-1")] = val.decode("utf-8", "replace")
            blobs.append(key + b"\x00" + val)
        elif ctype in (b"eXIf",):
            blobs.append(body)
        elif ctype == b"caBX":  # C2PA manifest store
            c2pa = True
            blobs.append(body)
        elif ctype == b"IEND":
            tail = data[i + 12:i + 12 + 2_000_000]
            if tail:
                blobs.append(tail)  # metadata appended after the PNG proper
            break
        i += 12 + length
    return b"\n".join(blobs), c2pa, text


def _webp_metadata(data: bytes) -> tuple[bytes, bool]:
    blobs, c2pa, i = [], False, 12
    while i + 8 <= len(data):
        fourcc, size = data[i:i + 4], struct.unpack("<I", data[i + 4:i + 8])[0]
        body = data[i + 8:i + 8 + size]
        if fourcc in (b"EXIF", b"XMP ", b"C2PA"):
            blobs.append(body)
            if fourcc == b"C2PA" or b"c2pa" in body:
                c2pa = True
        i += 8 + size + (size & 1)
    return b"\n".join(blobs), c2pa


def extract_metadata(content: bytes) -> dict:
    fmt, blob, c2pa, text = "unknown", b"", False, {}
    try:
        if content[:2] == b"\xff\xd8":
            fmt = "jpeg"
            blob, c2pa = _jpeg_metadata(content)
        elif content[:8] == b"\x89PNG\r\n\x1a\n":
            fmt = "png"
            blob, c2pa, text = _png_metadata(content)
        elif content[:4] == b"RIFF" and content[8:12] == b"WEBP":
            fmt = "webp"
            blob, c2pa = _webp_metadata(content)
    except (struct.error, IndexError, ValueError):
        pass  # a malformed container simply yields less metadata
    return {"format": fmt, "blob": blob, "c2pa": c2pa, "png_text": text}


def _camera_info(content: bytes) -> dict:
    """EXIF read from the ORIGINAL bytes (the pipeline converts the image to RGB, which drops EXIF)."""
    info = {"make": None, "model": None, "software": None, "taken_at": None, "description": None}
    try:
        exif = Image.open(BytesIO(content)).getexif()
        info["make"] = (exif.get(271) or None)
        info["model"] = (exif.get(272) or None)
        info["software"] = (exif.get(305) or None)
        info["description"] = (exif.get(270) or None)
        sub = exif.get_ifd(0x8769)
        info["taken_at"] = sub.get(36867) or exif.get(306) or None
    except Exception:  # noqa: BLE001 - unreadable EXIF is just "no camera data"
        pass
    return {k: (str(v).strip() if v else None) for k, v in info.items()}


# ── the check ───────────────────────────────────────────────────────────────────────────────
def assess_authenticity(image: Image.Image, content: bytes | None = None) -> dict:
    if not content:
        return {"status": "inconclusive", "risk": "inconclusive", "ai_generated": False, "generator": None, "signals": [],
                "camera": None, "content_credentials_present": False, "version": AUTHENTICITY_VERSION, "limitations": LIMITATIONS}

    meta = extract_metadata(content)
    camera = _camera_info(content)
    # UTF-16 text (EXIF UserComment written by Stable Diffusion WebUI etc.) has a NUL between every character,
    # so look at a NUL-stripped copy as well as the raw bytes
    raw = meta["blob"]
    blob = raw + b"\n" + raw.replace(b"\x00", b"")
    lower = blob.lower()
    signals: list[dict] = []
    generator = None

    for source_type in SOURCE_TYPES:
        if source_type in lower:
            signals.append({"kind": "digital_source_type", "detail": "Marked as AI-generated (IPTC DigitalSourceType)"})
            break

    for label, pattern in GENERATORS:
        if pattern.search(blob):
            signals.append({"kind": "generator_name", "detail": f"Metadata names the generator: {label}"})
            generator = generator or label

    text = meta["png_text"]
    params = text.get("parameters", "")
    if not params and (b"Steps:" in blob and (b"Sampler:" in blob or b"CFG scale" in blob)):
        params = "Steps: Sampler:"  # same parameter block, stored in EXIF/XMP of a JPEG/WebP instead of a PNG chunk
    if "Steps:" in params and ("Sampler:" in params or "CFG scale" in params):
        signals.append({"kind": "generation_parameters", "detail": "Stable Diffusion generation parameters found in the file"})
        generator = generator or "Stable Diffusion"
    if "prompt" in text and "workflow" in text and '"class_type"' in (text["prompt"] + text["workflow"]):
        signals.append({"kind": "png_text", "detail": "ComfyUI workflow found in the PNG"})
        generator = generator or "ComfyUI"
    for key in ("invokeai_metadata", "invokeai_graph", "sd-metadata", "Dream", "fooocus_scheme"):
        if key in text:
            signals.append({"kind": "png_text", "detail": f"Generator metadata key '{key}' found in the PNG"})
            generator = generator or ("InvokeAI" if "invoke" in key or key in ("sd-metadata", "Dream") else "Fooocus")
            break

    software_text = " ".join(filter(None, [camera["software"], camera["description"]])).encode("utf-8", "ignore")
    for label, pattern in GENERATORS:
        if software_text and pattern.search(software_text) and not any(label in s["detail"] for s in signals):
            signals.append({"kind": "exif_software", "detail": f"EXIF Software/description names the generator: {label}"})
            generator = generator or label

    ai_generated = bool(signals)
    if meta["c2pa"] and not ai_generated:
        signals.append({"kind": "content_credentials", "detail": "Content Credentials (C2PA) present, with no AI-generation claim"})

    has_camera = bool(camera["make"] or camera["model"])
    width, height = image.size
    typical_ai_size = (width, height) in _COMMON_AI_SIZES
    suspicious = (not ai_generated) and (not has_camera) and typical_ai_size and meta["format"] in ("png", "webp")

    if ai_generated:
        status, risk = "ai_generated", "high"
    elif suspicious:
        status, risk = "suspicious", "medium"
        signals.append({"kind": "weak", "detail": f"No camera data and a typical AI output size ({width}x{height})"})
    elif has_camera and camera["taken_at"]:
        status, risk = "camera_original", "low"
    else:
        status, risk = "inconclusive", "inconclusive"

    return {
        "status": status,
        "risk": risk,
        "ai_generated": ai_generated,
        "generator": generator,
        "signals": signals,
        "camera": camera,
        "content_credentials_present": bool(meta["c2pa"]),
        "format": meta["format"],
        "version": AUTHENTICITY_VERSION,
        "limitations": LIMITATIONS,
    }
