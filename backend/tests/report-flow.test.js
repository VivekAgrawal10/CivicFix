/**
 * report-flow.test.js — report creation + XP policy against the real MySQL data layer and a fake AI service.
 * Needs no MySQL server by default (SQLite adapter); TEST_DB=mysql runs the same checks on real MySQL.
 *
 * Verifies: non-civic photos are rejected (422, nothing stored, no XP); accepted reports store the AI
 * analysis and keep the reward PENDING; the reward is granted exactly once after independent
 * verification (another citizen's confirmation); the daily cap stops farming.
 */
const assert = require('assert');
const http = require('http');
const path = require('path');
const fs = require('fs');

// ── fake AI service ───────────────────────────────────────────────────────────
const fakeAi = http.createServer((req, res) => {
  const chunks = [];
  req.on('data', (c) => chunks.push(c));
  req.on('end', () => {
    const body = Buffer.concat(chunks).toString('latin1');
    const aigen = body.includes('AIGEN-ME');
    const rejected = aigen || body.includes('REJECT-ME');
    res.writeHead(rejected ? 422 : 200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ ok: true, error: null, meta: {}, data: rejected
      ? aigen ? { analysis_status: 'rejected_ai_generated', rejection_code: 'AI_GENERATED_IMAGE', message: 'This image appears to be AI-generated.', authenticity: { ai_generated: true, generator: 'DALL-E' }, decision: { outcome: 'rejected', manual_review_required: false, xp_eligible: false } }
      : { analysis_status: 'rejected_non_civic', message: 'This looks like a document, not a civic issue.', relevance: { status: 'non_civic', kind: 'document' }, decision: { outcome: 'rejected', manual_review_required: false, xp_eligible: false } }
      : { analysis_status: 'completed_with_degraded_models', image_hash: 'f0f0f0f0f0f0f0f0', relevance: { status: 'civic', kind: 'pothole', confidence: 0.8, method: 'clip_zero_shot_pretrained' }, severity: { label: 'severe' }, duplicates: { duplicate_candidate: false }, decision: { outcome: 'accepted_pending_verification', manual_review_required: false, xp_eligible: true } } }));
  });
});

// Real models + real SQL (in-memory SQLite adapter, or a real MySQL server with TEST_DB=mysql).
// Only the side channels (socket / push) are stubbed.
const testDb = require('./helpers/testDb');
const stub = (rel, exports) => { const id = require.resolve(path.join(__dirname, '..', rel)); require.cache[id] = { id, filename: id, loaded: true, exports }; };
stub('src/config/socket.js', { emitToUser: () => {} });
stub('src/utils/fcm.js', { sendPushNotification: async () => {} });

const mockRes = () => { const r = { code: 200, body: null }; r.status = (c) => { r.code = c; return r; }; r.json = (b) => { r.body = b; return r; }; return r; };
const uploads = path.join(__dirname, '../uploads');

(async () => {
  console.log(`Backend under test: ${testDb.label()}`);
  await testDb.setup();
  const User = require('../src/models/User');
  const Report = require('../src/models/Report');
  const credsOf = async (id) => (await User.findById(id)).civicCreds;
  await new Promise((r) => fakeAi.listen(0, r));
  process.env.AI_SERVICE_URL = `http://127.0.0.1:${fakeAi.address().port}`;
  fs.mkdirSync(uploads, { recursive: true });
  fs.writeFileSync(path.join(uploads, 'ok-test.jpg'), 'real civic bytes');
  fs.writeFileSync(path.join(uploads, 'bad-test.jpg'), 'REJECT-ME document bytes');
  fs.writeFileSync(path.join(uploads, 'aigen-test.jpg'), 'AIGEN-ME generated bytes');
  const { createReport, confirmReport, updateReportStatus } = require('../src/controllers/report.controller');
  const base = { title: 'Pothole', description: 'deep', category: 'pothole', location: { type: 'Point', coordinates: [76.36, 30.35] } };
  let passed = 0;
  const t = async (name, fn) => { try { await fn(); console.log(`  ✅ ${name}`); passed++; } catch (e) { console.error(`  ❌ ${name}: ${e.stack}`); process.exitCode = 1; } };

  const mkUser = (name) => User.create({ name, email: `${name}@t.com`, password: 'Passw0rd!' });
  const alice = await mkUser('alice'); const bob = await mkUser('bob'); await mkUser('admin');
  const START = 50; // new users start with 50 CivicCreds

  await t('non-civic photo -> 422, nothing stored, no XP', async () => {
    const res = mockRes();
    await createReport({ body: { ...base, images: ['/uploads/bad-test.jpg'] }, user: { _id: alice._id } }, res, assert.ifError);
    assert.strictEqual(res.code, 422); assert.strictEqual(res.body.code, 'NON_CIVIC_IMAGE');
    assert.strictEqual(await Report.count(), 0); assert.strictEqual(await credsOf(alice._id), START);
  });

  await t('AI-generated photo -> 422 AI_GENERATED_IMAGE, nothing stored, no XP', async () => {
    const res = mockRes();
    await createReport({ body: { ...base, images: ['/uploads/aigen-test.jpg'] }, user: { _id: alice._id } }, res, assert.ifError);
    assert.strictEqual(res.code, 422); assert.strictEqual(res.body.code, 'AI_GENERATED_IMAGE');
    assert.strictEqual(await Report.count(), 0); assert.strictEqual(await credsOf(alice._id), START);
  });

  let report;
  await t('civic photo -> stored with AI analysis, reward pending (not paid)', async () => {
    const res = mockRes();
    await createReport({ body: { ...base, images: ['/uploads/ok-test.jpg'] }, user: { _id: alice._id } }, res, assert.ifError);
    assert.strictEqual(res.code, 201); report = res.body.data;
    assert.strictEqual(report.aiAnalysis.outcome, 'accepted_pending_verification');
    assert.strictEqual(report.aiAnalysis.imageHash, 'f0f0f0f0f0f0f0f0');
    assert.deepStrictEqual(report.images, ['/uploads/ok-test.jpg']);
    assert.ok(report._id);
  });
  // priority: client did not pass priority, AI says severe -> 'high'
  await t('AI severity seeds priority; reward stays pending', async () => {
    assert.strictEqual(report.priority, 'high');
    assert.strictEqual(report.rewardPending, true); assert.strictEqual(report.rewardGranted, false);
    assert.strictEqual(await credsOf(alice._id), START);
  });

  await t('report with no photo is allowed but flagged for manual review', async () => {
    const res = mockRes();
    await createReport({ body: { ...base }, user: { _id: alice._id } }, res, assert.ifError);
    assert.strictEqual(res.code, 201); assert.strictEqual(res.body.data.aiAnalysis.manualReviewRequired, true);
  });

  await t('image hash of a nearby report is passed to the AI service for duplicate detection', async () => {
    assert.deepStrictEqual(await Report.hashesNear(30.35, 76.36, 150), ['f0f0f0f0f0f0f0f0']);
    assert.deepStrictEqual(await Report.hashesNear(31.35, 77.36, 150), []);
  });

  await t('own confirmation is refused', async () => {
    const res = mockRes();
    await confirmReport({ params: { id: report._id }, body: {}, user: { _id: alice._id } }, res, assert.ifError);
    assert.strictEqual(res.code, 400); assert.strictEqual(await credsOf(alice._id), START);
  });

  await t('another citizen confirming pays the submitter once, and the confirmer', async () => {
    const res = mockRes();
    await confirmReport({ params: { id: report._id }, body: {}, user: { _id: bob._id } }, res, assert.ifError);
    assert.strictEqual(res.code, 200);
    assert.strictEqual(await credsOf(alice._id), START + 25); assert.strictEqual(await credsOf(bob._id), START + 15);
    assert.strictEqual((await Report.findById(report._id)).rewardGranted, true);
    // admin status change afterwards must NOT pay again
    await updateReportStatus({ params: { id: report._id }, body: { status: 'assigned' }, user: { _id: alice._id } }, mockRes(), assert.ifError);
    assert.strictEqual(await credsOf(alice._id), START + 25);
  });

  await t('admin triage (status past pending) also counts as verification — exactly once', async () => {
    const res = mockRes();
    await createReport({ body: { ...base, title: 'Triage me' }, user: { _id: bob._id } }, res, assert.ifError);
    const id = res.body.data._id;
    await updateReportStatus({ params: { id }, body: { status: 'assigned' }, user: { _id: alice._id } }, mockRes(), assert.ifError);
    await updateReportStatus({ params: { id }, body: { status: 'in_progress' }, user: { _id: alice._id } }, mockRes(), assert.ifError);
    assert.strictEqual(await credsOf(bob._id), START + 15 + 25);
  });

  await t('daily cap blocks reward farming (max 5 submit rewards / 24h)', async () => {
    const carol = await mkUser('carol');
    for (let i = 0; i < 7; i++) {
      const res = mockRes();
      await createReport({ body: { ...base, images: ['/uploads/ok-test.jpg'] }, user: { _id: carol._id } }, res, assert.ifError);
      await updateReportStatus({ params: { id: res.body.data._id }, body: { status: 'assigned' }, user: { _id: alice._id } }, mockRes(), assert.ifError);
    }
    assert.strictEqual(await credsOf(carol._id), START + 5 * 25);
  });

  fs.unlinkSync(path.join(uploads, 'ok-test.jpg')); fs.unlinkSync(path.join(uploads, 'bad-test.jpg')); fs.unlinkSync(path.join(uploads, 'aigen-test.jpg'));
  fakeAi.close();
  await testDb.teardown();
  console.log(`\n${passed} checks passed — backend: ${testDb.label()}`);
  if (process.exitCode) console.log('SOME CHECKS FAILED');
})();
